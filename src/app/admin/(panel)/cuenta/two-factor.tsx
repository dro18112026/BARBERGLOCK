"use client";

import { useState, useTransition } from "react";
import { btnPrimary, btnSecondary, input } from "@/components/ui";
import { confirmTotpEnroll, disableTotp, startTotpEnroll } from "./actions";

type Props = { enabledFactorId: string | null };

export function TwoFactor({ enabledFactorId }: Props) {
  const [pending, startTransition] = useTransition();
  const [enroll, setEnroll] = useState<{ factorId: string; qr: string; secret: string } | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState(false);

  if (enabledFactorId && !enroll) {
    return (
      <div className="flex flex-col gap-3">
        <p className="text-lg">
          ✅ <strong>Activada.</strong> Cada vez que inicies sesión te pediremos el código de tu app.
        </p>
        {error && <p role="alert" className="font-bold text-barber">{error}</p>}
        <button
          type="button"
          disabled={pending}
          className={btnSecondary}
          onClick={() => {
            if (!window.confirm("¿Desactivar la verificación en dos pasos? Tu cuenta quedará menos protegida.")) return;
            startTransition(async () => {
              const r = await disableTotp(enabledFactorId);
              setError(r.ok ? null : (r.error ?? null));
            });
          }}
        >
          {pending ? "Desactivando…" : "Desactivar"}
        </button>
      </div>
    );
  }

  if (done) {
    return <p className="text-lg font-bold text-steel">✅ Listo, la verificación en dos pasos quedó activada.</p>;
  }

  if (!enroll) {
    return (
      <div className="flex flex-col gap-3">
        <p className="text-lg">
          Además de tu contraseña, se pedirá un código de 6 números que cambia cada 30 segundos
          en tu celular. Así, aunque alguien sepa tu contraseña, no puede entrar.
        </p>
        <p className="text-smoke">
          Necesitas una app de autenticación, por ejemplo <strong>Google Authenticator</strong> o{" "}
          <strong>Microsoft Authenticator</strong> (gratis en App Store y Google Play).
        </p>
        {error && <p role="alert" className="font-bold text-barber">{error}</p>}
        <button
          type="button"
          disabled={pending}
          className={btnPrimary}
          onClick={() =>
            startTransition(async () => {
              const r = await startTotpEnroll();
              if (r.ok) {
                setEnroll({ factorId: r.factorId, qr: r.qr, secret: r.secret });
                setError(null);
              } else setError(r.error);
            })
          }
        >
          {pending ? "Preparando…" : "Activar verificación en dos pasos"}
        </button>
      </div>
    );
  }

  return (
    <form
      className="flex flex-col gap-4"
      onSubmit={(e) => {
        e.preventDefault();
        startTransition(async () => {
          const r = await confirmTotpEnroll(enroll.factorId, code);
          if (r.ok) {
            setDone(true);
            setEnroll(null);
          } else setError(r.error ?? null);
        });
      }}
    >
      <ol className="ml-5 list-decimal text-lg">
        <li>En tu app de autenticación, toca <strong>+</strong> / &quot;Agregar cuenta&quot;.</li>
        <li>Escanea este código QR.</li>
        <li>Escribe abajo el código de 6 números que aparece.</li>
      </ol>
      {/* The QR is an SVG data URL generated by Supabase (allowed by CSP img-src data:). */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={enroll.qr} alt="Código QR para la app de autenticación" className="mx-auto h-52 w-52 rounded bg-paper p-2" />
      <details className="text-sm text-smoke">
        <summary className="cursor-pointer">¿No puedes escanear? Escribe esta clave en la app</summary>
        <code className="mt-1 block break-all rounded bg-bone p-2 font-mono text-ink">{enroll.secret}</code>
      </details>
      <input
        value={code}
        onChange={(e) => setCode(e.target.value)}
        inputMode="numeric"
        autoComplete="one-time-code"
        maxLength={7}
        required
        placeholder="123456"
        className={`${input} text-center font-display text-3xl tracking-[0.3em]`}
      />
      {error && <p role="alert" className="font-bold text-barber">{error}</p>}
      <button type="submit" disabled={pending} className={btnPrimary}>
        {pending ? "Verificando…" : "Confirmar y activar"}
      </button>
    </form>
  );
}
